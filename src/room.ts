import { join } from 'node:path'
import { backend, isRouted } from './backend.ts'
import { roomsHome } from './config.ts'
import { Record, hhmm, now, slug } from './record.ts'

// A room is a folder in ROOMS_HOME:
//   BRIEF.md       the room's charter and wiring (lead_session, team, prd state)
//   PRD.md         the feature's product view; agreed once, then refinements
//   now-head.md    the lead's current position (phase, waiting, resume)
//   items/Tnn-*.md        work items
//   decisions/Dnn-*.md    decisions (D), premises (P), asks (A), todos for the human
//   refinements/RFnn-*.md changes to an agreed PRD
//   notes/         long-form notes, one writer per file
//   README.md      generated by `rooms status`; never edited by hand

export const ITEM_STATES = ['todo', 'doing', 'blocked', 'review', 'done', 'dropped'] as const
export const OPEN_ITEM = new Set(['todo', 'doing', 'blocked', 'review'])
export const DECISION_PREFIX: { [type: string]: string } = { decision: 'D', premise: 'P', ask: 'A', todo: 'D' }

export class Room {
  name: string
  dir: string

  constructor(name: string) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) throw new Error(`bad room name "${name}": lowercase letters, digits and dashes`)
    this.name = name
    this.dir = join(roomsHome(), name)
  }

  static all(): Room[] {
    return backend()
      .list(roomsHome())
      .filter(d => {
        if (!d.dir) return false
        try {
          return backend().exists(join(roomsHome(), d.name, 'BRIEF.md'))
        } catch (e) {
          // A room on the hub that can't be asked (hub down) stays listed, so
          // overviews can say it is unreachable; the local rooms are unaffected.
          if (isRouted(d.name)) return true
          throw e
        }
      })
      .map(d => new Room(d.name))
  }

  exists(): boolean {
    return backend().exists(join(this.dir, 'BRIEF.md'))
  }

  must(): this {
    if (!this.exists()) throw new Error(`no room "${this.name}" in ${roomsHome()}`)
    return this
  }

  get brief(): Record {
    return Record.load(join(this.dir, 'BRIEF.md'))
  }

  get head(): Record {
    const p = join(this.dir, 'now-head.md')
    return backend().exists(p) ? Record.load(p) : new Record(p, '---\n---\n')
  }

  records(sub: string): Record[] {
    const d = join(this.dir, sub)
    return backend()
      .list(d)
      .map(e => e.name)
      .filter(f => /^[A-Z]+\d+.*\.md$/.test(f))
      .sort(byId)
      .map(f => Record.load(join(d, f)))
  }

  items(): Record[] {
    return this.records('items')
  }

  decisions(): Record[] {
    return this.records('decisions')
  }

  refinements(): Record[] {
    return this.records('refinements')
  }

  find(id: string): Record {
    const sub = id.startsWith('T') ? 'items' : id.startsWith('RF') ? 'refinements' : 'decisions'
    const r = this.records(sub).find(r => r.get('id') === id)
    if (!r) throw new Error(`${this.name}: no record ${id}`)
    return r
  }

  nextId(prefix: string): string {
    const sub = prefix === 'T' ? 'items' : prefix === 'RF' ? 'refinements' : 'decisions'
    const used = this.records(sub)
      .map(r => r.get('id'))
      .filter(id => id.startsWith(prefix) && /^\d+$/.test(id.slice(prefix.length)))
      .map(id => Number(id.slice(prefix.length)))
    return prefix + String(Math.max(0, ...used) + 1).padStart(2, '0')
  }

  create(sub: string, id: string, title: string, fields: [string, string | string[]][], sections: [string, string][]): Record {
    const r = new Record(join(this.dir, sub, `${id}-${slug(title)}.md`), '---\n---\n')
    r.set('id', id)
    r.set('title', title)
    for (const [k, v] of fields) r.set(k, v)
    for (const [n, b] of sections) r.setSection(n, b)
    r.save()
    return r
  }

  prd(): Record | undefined {
    const p = join(this.dir, 'PRD.md')
    return backend().exists(p) ? Record.load(p) : undefined
  }

  // Building is locked while a PRD exists and isn't agreed.
  buildLocked(): boolean {
    const prd = this.prd()
    return !!prd && prd.get('status') !== 'agreed'
  }

  isClosed(): boolean {
    return !!this.brief.get('closed')
  }

  isPaused(): boolean {
    return !!this.brief.get('paused')
  }

  leadSession(): string {
    return this.brief.get('lead_session')
  }
}

export function logLine(r: Record, by: string, text: string): void {
  r.appendTo('Log', `- ${hhmm()} ${by}: ${text.replace(/\s+/g, ' ').trim()}`)
  r.set('updated', now())
}

export function by(): string {
  return process.env.ROOMS_AS || process.env.TRACKER_AS || 'lead'
}

function byId(a: string, b: string): number {
  const na = Number(a.match(/^[A-Z]+(\d+)/)?.[1] ?? 0)
  const nb = Number(b.match(/^[A-Z]+(\d+)/)?.[1] ?? 0)
  return a.match(/^[A-Z]+/)![0].localeCompare(b.match(/^[A-Z]+/)![0]) || na - nb
}
